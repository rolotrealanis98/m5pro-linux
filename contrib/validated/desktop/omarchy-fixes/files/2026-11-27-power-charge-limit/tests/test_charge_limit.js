const assert = require("assert")
const L = require("../ChargeLimit.js")

assert.deepStrictEqual(L.parse("end\t80\nstart\t75\nsaved\t80\n"), { end: 80, start: 75, saved: 80 })
assert.deepStrictEqual(L.parse("end\t<img src=x>\nsaved\t\nother\t5\nend 80"), {})
assert.deepStrictEqual(L.parse("end\t9999\nsaved\t-5"), {})
assert.strictEqual(L.state({}).supported, false)
assert.strictEqual(L.state({}).persistent, 0)

let s = L.state({ end: 80, start: 75, saved: 80 })
assert.deepStrictEqual([s.supported, s.end, s.start, s.saved, s.fullOnce, s.persistent], [true, 80, 75, 80, false, 80])
s = L.state({ end: 100, start: 95, saved: 85 })
assert.deepStrictEqual([s.fullOnce, s.persistent], [true, 85])
s = L.state({ end: 100, start: 95, saved: 100 })
assert.deepStrictEqual([s.fullOnce, s.persistent], [false, 100])
s = L.state({ end: 100 })
assert.deepStrictEqual([s.fullOnce, s.persistent, s.saved], [false, 100, 0])
s = L.state({ end: 30, saved: 30 })
assert.deepStrictEqual([s.persistent, s.saved], [50, 0])

assert.strictEqual(L.clamp(49.4), 50)
assert.strictEqual(L.clamp(84.6), 85)
assert.strictEqual(L.clamp(140), 100)
assert.strictEqual(L.clamp("x"), 100)
assert.strictEqual(L.argument(85), "85")
assert.strictEqual(L.argument(100), "100")
assert.strictEqual(L.argument("full"), "full")
assert.strictEqual(L.argument(49), "")
assert.strictEqual(L.argument("85; rm -rf ~"), "")
assert.strictEqual(L.argument(undefined), "")
console.log("ok")
