#!/usr/bin/env python3
"""mk-esp.py - stage the ESP files of the J716s Omarchy-chain test (U-Boot -> Limine -> our kernel).

Never touches the machine. Inputs are pinned by sha256; outputs go to
  out/esp/                  public files, at their ESP paths (m1n1/boot.bin, EFI/BOOT/BOOTAA64.EFI,
                            limine.conf, m5chain/Image)
  private/esp/m5chain/      the FTAB-bearing initramfs (0600, never committed)
and SHA256SUMS next to each. build.sh must have run (out/boot-b1.bin).

  Limine  BOOTAA64.EFI from Arch Linux ARM extra limine-12.9.6-1 (what Omarchy's Apple images install
          from arm-mirror.omarchy.org; omarchy-mac-boot copies /usr/share/limine/BOOTAA64.EFI).
          Package sha256 checked against the repository database (inputs/pkgs/expected.sha).
  kernel  Image-7.3.0-ga0f2f30c967b.gz (the 87-patch daily kernel) decompressed: the arm64 EFI stub
          is in the uncompressed Image (no EFI_ZBOOT); Limine's efi protocol loads a PE as is.
  initrd  the daily-wifi FTAB initramfs, unchanged (the EFI stub loads it from the ESP: initrd=).
  DTB     none on the ESP: U-Boot passes m1n1's prepared tree (${fdtcontroladdr}) to Limine as the
          EFI device-tree table, and both entries use it (no dtb_path).
"""
import hashlib, os, pathlib, shutil, subprocess, sys, tarfile, gzip, lzma, io, struct

H = pathlib.Path.home()
W = pathlib.Path(os.environ.get("OMARCHY_CHAIN_WORK", H / "Work/agents/omarchy-chain"))
OUT, PRIV = W / "out", W / "private"
ESP, PESP = OUT / "esp", PRIV / "esp"
K = H / "Work/agents/next-daily/images/Image-7.3.0-ga0f2f30c967b.gz"
IRD = H / "Work/agents/next-daily/payloads/private/initramfs-ftab.cpio.gz"
LIMINE_PKG = W / "inputs/pkgs/limine-12.9.6-1-aarch64.pkg.tar.xz"
B1 = OUT / "boot-b1.bin"
PINS = {K: "0f302e9a7a05be12884d38e2aff794ec64ae094619eb9d06df8e5bac6e5106fb",
        IRD: "cffbbaf1030d224ca092c586aa25ab0ef2a93db5a1e2701aa3bd0d5618b2fbfa",
        LIMINE_PKG: "09d6f6bc8990bb7b53688b06b2ab538e453e129fb35406d6a6bd5bb053f25642"}
# The daily's bootargs (daily-wifi-20261107-4feff24c recipe), minus nothing; plus root= for the record
# (the initramfs mounts m5.root=; the kernel ignores root= once /init exists) and a marker per entry.
BOOTARGS = ("earlycon=efifb keep_bootcon console=tty0 loglevel=8 pd_ignore_unused clk_ignore_unused "
            "no_console_suspend nvme_apple.flush_interval=0 m5.root=/dev/nvme0n1p5 "
            "kvm-arm.wfi_trap_policy=trap pcie_aspm=off root=/dev/nvme0n1p5")

sha = lambda b: hashlib.sha256(b).hexdigest()
b2 = lambda b: hashlib.blake2b(b).hexdigest()   # Limine's #hash is BLAKE2B-512


def write(path, data, mode=0o644):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700 if PRIV in path.parents else 0o755)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "wb") as f:
        f.write(data)
    os.chmod(path, mode)


def main():
    for p, h in PINS.items():
        assert sha(p.read_bytes()) == h, f"{p} changed"
    assert B1.exists(), "run build.sh first"
    shutil.rmtree(ESP, ignore_errors=True)
    shutil.rmtree(PESP, ignore_errors=True)

    # Limine EFI binary out of the verified package
    with tarfile.open(fileobj=io.BytesIO(lzma.decompress(LIMINE_PKG.read_bytes()))) as t:
        efi = t.extractfile("usr/share/limine/BOOTAA64.EFI").read()
        pkginfo = t.extractfile(".PKGINFO").read().decode()
    assert efi[:2] == b"MZ"
    pe = struct.unpack_from("<I", efi, 0x3c)[0]
    assert efi[pe:pe + 4] == b"PE\0\0" and struct.unpack_from("<H", efi, pe + 4)[0] == 0xaa64, "not an arm64 PE"

    # kernel: decompress; check the arm64 Image header and the EFI stub's PE header
    img = gzip.decompress(K.read_bytes())
    assert img[:2] == b"MZ" and struct.unpack_from("<I", img, 0x38)[0] == 0x644d5241, "not an arm64 EFI-stub Image"
    kpe = struct.unpack_from("<I", img, 0x3c)[0]
    assert img[kpe:kpe + 4] == b"PE\0\0" and struct.unpack_from("<H", img, kpe + 4)[0] == 0xaa64
    ird = IRD.read_bytes()

    conf = f"""# J716s Omarchy-chain test: m1n1 stage 2 -> U-Boot -> Limine -> the 87-patch daily kernel.
# Not an Omarchy install. Generated by contrib/pending/installer/omarchy-chain/mk-esp.py.
# Layout as omarchy-mac-boot writes it (ESP:/limine.conf, a /+Omarchy directory, protocol: efi),
# with a short timeout so the stage-1 watchdog (150 s) is never spent in the menu.
timeout: 5
default_entry: 2
remember_last_entry: no
verbose: yes
hash_mismatch_panic: yes
interface_branding: Omarchy Bootloader (J716s chain test)
interface_branding_color: 9ece6a
term_background: 1a1b26
backdrop: 1a1b26
term_foreground: c0caf5

/+Omarchy chain test
  //J716s 7.3.0-ga0f2f30c967b, EFI stub
    comment: kernel EFI stub; initramfs by initrd=; device tree = U-Boot's EFI table (m1n1's)
    protocol: efi
    path: boot():/m5chain/Image#{b2(img)}
    cmdline: initrd=/m5chain/initramfs-ftab.cpio.gz m5.chain=limine-efi {BOOTARGS}
  //J716s 7.3.0-ga0f2f30c967b, Limine linux protocol
    comment: Limine loads the Image itself and exits boot services; same device tree
    protocol: linux
    path: boot():/m5chain/Image#{b2(img)}
    module_path: boot():/m5chain/initramfs-ftab.cpio.gz#{b2(ird)}
    cmdline: m5.chain=limine-linux {BOOTARGS}
"""
    files = {"m1n1/boot.bin": B1.read_bytes(), "EFI/BOOT/BOOTAA64.EFI": efi,
             "limine.conf": conf.encode(), "m5chain/Image": img}
    for rel, data in files.items():
        write(ESP / rel, data)
    write(PESP / "m5chain/initramfs-ftab.cpio.gz", ird, 0o600)
    for d in (PRIV, PESP, PESP / "m5chain"):
        os.chmod(d, 0o700)

    lines = [f"{sha(d)}  {r}" for r, d in files.items()]
    (ESP / "SHA256SUMS").write_text("\n".join(lines) + "\n")
    write(PESP / "SHA256SUMS", f"{sha(ird)}  m5chain/initramfs-ftab.cpio.gz\n".encode(), 0o600)

    pkgver = [l for l in pkginfo.splitlines() if l.startswith("pkgver")][0]
    total = sum(len(d) for d in files.values()) + len(ird)
    print(f"limine   {pkgver}  BOOTAA64.EFI {len(efi)} B  sha256 {sha(efi)}")
    print(f"Image    {len(img)} B  sha256 {sha(img)}  blake2b {b2(img)[:16]}..")
    print(f"initrd   {len(ird)} B  (private)")
    print(f"boot.bin {len(files['m1n1/boot.bin'])} B  sha256 {sha(files['m1n1/boot.bin'])}")
    print(f"total new ESP bytes {total} ({total / 2**20:.1f} MiB), plus boot.bin.prev = the running daily")
    print((ESP / "SHA256SUMS").read_text(), end="")


if __name__ == "__main__":
    main()
