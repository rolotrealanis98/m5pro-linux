#!/usr/bin/env python3
"""Read, persist, and live-apply mouse, trackpad, and cursor settings for Hyprland."""

import json
import os
import re
import subprocess
import sys
import tempfile

HOME = os.path.expanduser("~")
CONFIG_JSON = os.path.join(HOME, ".config", "hypr", "pointer-tuning.json")
CONFIG_LUA = os.path.join(HOME, ".config", "hypr", "pointer-tuning.lua")

DEFAULTS = {
    "trackpad_scroll_factor": 1.0,
    "trackpad_scroll_accel": 1.0,
    "trackpad_tracking": 0.6875,
    "trackpad_gain": 1.0,
    "trackpad_natural_scroll": True,
    "trackpad_tap_to_click": True,
    "trackpad_disable_while_typing": True,
    "trackpad_three_finger_drag": False,
    "mouse_sensitivity": 0.0,
    "mouse_scroll_factor": 1.0,
    "mouse_accel_profile": "adaptive",
    "mouse_natural_scroll": False,
    "cursor_size": 24,
}


def clamp(val, lo, hi, default):
    try:
        num = float(val)
        if num != num:  # NaN
            return default
        return max(lo, min(hi, num))
    except (TypeError, ValueError):
        return default


def sanitize(raw):
    data = dict(DEFAULTS)
    if isinstance(raw, dict):
        data["trackpad_scroll_factor"] = round(clamp(raw.get("trackpad_scroll_factor"), 0.1, 3.0, DEFAULTS["trackpad_scroll_factor"]), 3)
        data["trackpad_scroll_accel"] = round(clamp(raw.get("trackpad_scroll_accel"), 0.0, 1.0, DEFAULTS["trackpad_scroll_accel"]), 3)
        data["trackpad_tracking"] = round(clamp(raw.get("trackpad_tracking"), 0.0, 3.0, DEFAULTS["trackpad_tracking"]), 4)
        data["trackpad_gain"] = round(clamp(raw.get("trackpad_gain"), 0.4, 2.0, DEFAULTS["trackpad_gain"]), 3)
        data["trackpad_natural_scroll"] = bool(raw.get("trackpad_natural_scroll", DEFAULTS["trackpad_natural_scroll"]))
        data["trackpad_tap_to_click"] = bool(raw.get("trackpad_tap_to_click", DEFAULTS["trackpad_tap_to_click"]))
        data["trackpad_disable_while_typing"] = bool(raw.get("trackpad_disable_while_typing", DEFAULTS["trackpad_disable_while_typing"]))
        data["trackpad_three_finger_drag"] = bool(raw.get("trackpad_three_finger_drag", DEFAULTS["trackpad_three_finger_drag"]))
        data["mouse_sensitivity"] = round(clamp(raw.get("mouse_sensitivity"), -1.0, 1.0, DEFAULTS["mouse_sensitivity"]), 3)
        data["mouse_scroll_factor"] = round(clamp(raw.get("mouse_scroll_factor"), 0.2, 4.0, DEFAULTS["mouse_scroll_factor"]), 3)
        profile = raw.get("mouse_accel_profile", DEFAULTS["mouse_accel_profile"])
        data["mouse_accel_profile"] = profile if profile in ("adaptive", "flat") else DEFAULTS["mouse_accel_profile"]
        data["mouse_natural_scroll"] = bool(raw.get("mouse_natural_scroll", DEFAULTS["mouse_natural_scroll"]))
        size = int(round(clamp(raw.get("cursor_size"), 16, 64, DEFAULTS["cursor_size"])))
        data["cursor_size"] = size
    return data


def atomic_write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".tmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
        os.replace(tmp_path, path)
    except Exception:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)
        raise


def cursor_theme():
    theme = os.environ.get("XCURSOR_THEME", "Adwaita").strip()
    if not re.fullmatch(r"[A-Za-z0-9._-]+", theme):
        return "Adwaita"
    return theme


def generate_lua(cfg):
    def b(v):
        return "true" if v else "false"

    theme = cursor_theme()
    return f"""-- Auto-generated by rolo.pointer plugin. Do not edit by hand.
local C = dofile(os.getenv("HOME") .. "/.config/hypr/trackpad/curves.lua")

hl.config({{
  input = {{
    sensitivity = {cfg["mouse_sensitivity"]},
    accel_profile = "{cfg["mouse_accel_profile"]}",
    scroll_factor = {cfg["mouse_scroll_factor"]},
    natural_scroll = {b(cfg["mouse_natural_scroll"])},
  }},
}})

hl.device({{
  name = "apple-mtp-multi-touch",
  accel_profile = C.motion_profile({{ shape = "macos", tracking = {cfg["trackpad_tracking"]}, gain = {cfg["trackpad_gain"]} }}),
  scroll_points = C.scroll_points({{ accel = {cfg["trackpad_scroll_accel"]} }}),
  sensitivity = 0,
  scroll_factor = {cfg["trackpad_scroll_factor"]},
  natural_scroll = {b(cfg["trackpad_natural_scroll"])},
  scroll_method = "2fg",
  clickfinger_behavior = true,
  tap_to_click = {b(cfg["trackpad_tap_to_click"])},
  tap_button_map = "lrm",
  tap_and_drag = true,
  drag_lock = 1,
  drag_3fg = {1 if cfg["trackpad_three_finger_drag"] else 0},
  disable_while_typing = {b(cfg["trackpad_disable_while_typing"])},
  middle_button_emulation = false,
  left_handed = false,
}})

hl.exec_cmd("hyprctl setcursor {theme} {cfg["cursor_size"]}")
"""


def load_config():
    if os.path.exists(CONFIG_JSON):
        try:
            with open(CONFIG_JSON, "r", encoding="utf-8") as f:
                return sanitize(json.load(f))
        except Exception:
            pass
    return dict(DEFAULTS)


def save_and_apply(cfg, apply_cursor=True):
    atomic_write(CONFIG_JSON, json.dumps(cfg, indent=2) + "\n")
    atomic_write(CONFIG_LUA, generate_lua(cfg))
    subprocess.run(
        ["hyprctl", "eval", 'dofile(os.getenv("HOME") .. "/.config/hypr/pointer-tuning.lua")'],
        check=False,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    if apply_cursor:
        subprocess.run(
            ["hyprctl", "setcursor", cursor_theme(), str(cfg["cursor_size"])],
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )


def main():
    if len(sys.argv) < 2 or sys.argv[1] == "--read":
        cfg = load_config()
        if not os.path.exists(CONFIG_JSON) or not os.path.exists(CONFIG_LUA):
            atomic_write(CONFIG_JSON, json.dumps(cfg, indent=2) + "\n")
            atomic_write(CONFIG_LUA, generate_lua(cfg))
        print(json.dumps(cfg))
        return

    if sys.argv[1] == "--reset":
        cfg = dict(DEFAULTS)
        save_and_apply(cfg, apply_cursor=True)
        print(json.dumps(cfg))
        return

    if sys.argv[1] == "--write" and len(sys.argv) >= 3:
        prev = load_config()
        raw = json.loads(sys.argv[2])
        cfg = sanitize(raw)
        save_and_apply(cfg, apply_cursor=(cfg["cursor_size"] != prev["cursor_size"]))
        print(json.dumps(cfg))
        return

    sys.exit(1)


if __name__ == "__main__":
    main()
